#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize, uniffi::Enum)]
pub enum Orientation {
    Upright = 0,
    Reversed = 1,
}

impl Orientation {
    pub fn is_upright(&self) -> bool {
        matches!(self, Orientation::Upright)
    }

    pub fn is_reversed(&self) -> bool {
        matches!(self, Orientation::Reversed)
    }

    pub fn name_zh(&self) -> &'static str {
        match self {
            Orientation::Upright => "正位",
            Orientation::Reversed => "逆位",
        }
    }

    pub fn name_en(&self) -> &'static str {
        match self {
            Orientation::Upright => "Upright",
            Orientation::Reversed => "Reversed",
        }
    }
}

#[derive(Debug, Clone, Copy)]
pub struct StaticCardFacets {
    pub general_upright: &'static [&'static str],
    pub general_reversed: &'static [&'static str],
    pub love_upright: &'static str,
    pub love_reversed: &'static str,
    pub career_upright: &'static str,
    pub career_reversed: &'static str,
    pub spiritual_upright: &'static str,
    pub spiritual_reversed: &'static str,
    pub shadow_aspect: &'static str,
}

#[derive(Debug, Clone, Copy)]
pub struct StaticCardDefinition {
    pub id: u8,
    pub key: &'static str,
    pub arcana: ArcanaType,
    pub suit: Option<Suit>,
    pub rank: Option<Rank>,
    pub element: Element,
    pub name_en: &'static str,
    pub name_zh: &'static str,
    pub astrology: Option<&'static str>,
    pub hebrew_letter: Option<&'static str>,
    pub facets: StaticCardFacets,
}

impl StaticCardDefinition {
    pub fn to_owned_card(&self) -> Card {
        Card {
            id: self.id,
            key: self.key.to_string(),
            arcana: self.arcana,
            suit: self.suit,
            rank: self.rank,
            element: self.element,
            name_en: self.name_en.to_string(),
            name_zh: self.name_zh.to_string(),
            astrology: self.astrology.map(|s| s.to_string()),
            hebrew_letter: self.hebrew_letter.map(|s| s.to_string()),
            facets: CardFacets::new(
                self.facets.general_upright,
                self.facets.general_reversed,
                self.facets.love_upright,
                self.facets.love_reversed,
                self.facets.career_upright,
                self.facets.career_reversed,
                self.facets.spiritual_upright,
                self.facets.spiritual_reversed,
                self.facets.shadow_aspect,
            ),
        }
    }
}

