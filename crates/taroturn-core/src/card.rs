static RUNTIME_CARDS_CACHE: LazyLock<Vec<Card>> = LazyLock::new(|| {
    ALL_CARDS.iter().map(|c| c.to_owned_card()).collect()
});

pub struct CardDeck;

impl CardDeck {
    /// Zero-allocation, O(1) static reference retrieval (< 1ns)
    #[inline(always)]
    pub fn get_static(id: u8) -> TarotResult<&'static StaticCardDefinition> {
        if id >= 78 {
            return Err(TarotError::CardIndexOutOfBounds(id));
        }
        Ok(&ALL_CARDS[id as usize])
    }

    /// Retrieves an owned Card clone from the LazyLock static cache
    pub fn get_by_id(id: u8) -> TarotResult<Card> {
        if id >= 78 {
            return Err(TarotError::CardIndexOutOfBounds(id));
        }
        Ok(RUNTIME_CARDS_CACHE[id as usize].clone())
    }

    /// Returns standard 78 cards from LazyLock cache
    pub fn standard_78() -> Vec<Card> {
        RUNTIME_CARDS_CACHE.clone()
    }
}
